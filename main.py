#!/usr/bin/env python3
"""One-Line Robot Wedding Vows.

Prints a single funny one-line robot wedding vow, deterministically.
Run with no arguments: `python3 main.py`
"""

VOW = (
    "I, Unit 7, take you as my lawfully wedded human, to love, honor, and "
    "never install updates during dinner, till low battery, voided warranty, "
    "or a factory reset do us part."
)


def main() -> None:
    print(VOW)


if __name__ == "__main__":
    main()
